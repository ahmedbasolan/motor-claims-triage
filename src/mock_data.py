def _build_claim(
    claim_id: str,
    policy: Policy,
    driver_name: str,
    driver_age: int,
    license_years: int,
    vehicle_make: str,
    vehicle_model: str,
    vehicle_year: int,
    vehicle_value: float,
    days_ago: int,
    location: str,
    description: str,
    repair_cost: float,
    garage: str,
    vehicles_involved: int = 1,
    injury: bool = False,
    dispute: bool = False,
    extra_docs: list[dict] | None = None,
    accident_date: datetime | None = None,
    registration: str | None = None,
    docs: list[dict] | None = None,
) -> Claim:
    if accident_date is None:
        base = datetime(2024, 9, 15)
        accident_date = base.replace(day=max(1, base.day - days_ago))

    if docs is None:
        docs = [
            {
                "doc_type": "police_report",
                "description": f"Police report filed at {location}",
                "uploaded_at": accident_date,
            },
            {
                "doc_type": "photo",
                "description": f"Photos of vehicle damage at {location}",
                "uploaded_at": accident_date,
            },
        ]
        if extra_docs:
            docs.extend(extra_docs)
    doc_models = [DocumentMetadata(**d) for d in docs]

    return Claim(
        claim_id=claim_id,
        policy_number=policy.policy_number,
        vehicle=VehicleDetails(
            make=vehicle_make,
            model=vehicle_model,
            year=vehicle_year,
            registration_number=registration
            if registration is not None
            else policy.vehicle_registration,
            estimated_value=vehicle_value,
        ),
        driver=DriverDetails(
            name=driver_name,
            age=driver_age,
            license_tenure_years=license_years,
        ),
        accident=AccidentDetails(
            date=accident_date,
            location=location,
            description=description,
            police_report_summary=f"Officers responded to {location}. {description}",
            num_vehicles_involved=vehicles_involved,
            injury_reported=injury,
            liability_disputed=dispute,
        ),
        documents=doc_models,
        repair_estimate=RepairEstimate(
            estimated_cost=repair_cost,
            garage_name=garage,
            items=["Body repair", "Paint work", "Parts replacement"],
        ),
        submitted_at=accident_date,
    )


